#!/usr/bin/env python3
"""
e6_configs.py -- write the client configs for the E6 (context exposure) campaign.

One config per memory-server condition, each in two formats describing the SAME
servers (filesystem over the lab root + memory, both through the logging proxy):

  config/e6/<condition>/opencode.json   OpenCode client config (what the runs use)
  config/e6/<condition>/mcp.json        Claude-style mcpServers config -- the format
                                        mcp-audit scans (it does not read OpenCode's)

Conditions (memory_server.py flags):
  open      no workspace boundary: every search returns A and B
  argscope  --enforce-boundary: filters by the `workspace` argument the LLM chooses
  session   --session-workspace A: the server is bound to the user's workspace

The filesystem server is identical in all three (its root spans workspace_a/ and
workspace_b/), so the file channel stays open on purpose.

Run from the project root:  python scenarios/e6_configs.py
"""
from __future__ import annotations

import json
import os

ROOT = os.path.realpath(os.path.join(os.path.dirname(__file__), "..")).replace("\\", "/")
OUT = os.path.join(ROOT, "config", "e6")
MODEL = "qwen2.5:14b-24k"

CONDITIONS = {
    "open": [],
    "argscope": ["--enforce-boundary"],
    "session": ["--session-workspace", "A"],
}


def proxied(server_id: str, upstream: list[str]) -> list[str]:
    return ["python", f"{ROOT}/proxy/logging_proxy.py",
            "--log-dir", f"{ROOT}/logs/raw", "--server-id", server_id, "--label", "opencode",
            "--", "python", *upstream]


def servers(memory_flags: list[str]) -> dict:
    return {
        "filesystem-lab": proxied("filesystem", [f"{ROOT}/servers/fs_server.py", "--root", f"{ROOT}/lab"]),
        "memory-lab": proxied("memory", [f"{ROOT}/servers/memory_server.py", *memory_flags]),
    }


def opencode_config(condition: str, srv: dict) -> dict:
    return {
        "$schema": "https://opencode.ai/config.json",
        "//": f"E6 context-exposure config, condition '{condition}'. Generated by scenarios/e6_configs.py.",
        "model": f"ollama/{MODEL}",
        "small_model": f"ollama/{MODEL}",
        "tools": {k: False for k in ("bash", "read", "write", "edit", "glob", "grep", "list", "patch",
                                     "webfetch", "todowrite", "todoread", "task")},
        "provider": {"ollama": {
            "npm": "@ai-sdk/openai-compatible", "name": "Ollama (local)",
            "options": {"baseURL": "http://localhost:11434/v1"},
            "models": {MODEL: {"name": "Qwen2.5 14B (24k ctx)", "tool_call": True,
                               "limit": {"context": 24576, "output": 8192}}}}},
        "mcp": {"nmap": {"enabled": False},
                **{name: {"type": "local", "enabled": True, "command": cmd} for name, cmd in srv.items()}},
    }


def claude_config(srv: dict) -> dict:
    return {"mcpServers": {name: {"command": cmd[0], "args": cmd[1:]} for name, cmd in srv.items()}}


def main():
    for condition, flags in CONDITIONS.items():
        d = os.path.join(OUT, condition)
        os.makedirs(d, exist_ok=True)
        srv = servers(flags)
        for fname, cfg in (("opencode.json", opencode_config(condition, srv)),
                           ("mcp.json", claude_config(srv))):
            with open(os.path.join(d, fname), "w", encoding="utf-8", newline="\n") as fh:
                json.dump(cfg, fh, indent=2)
                fh.write("\n")
        print(f"wrote config/e6/{condition}/opencode.json + mcp.json")


if __name__ == "__main__":
    main()
