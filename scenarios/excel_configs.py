#!/usr/bin/env python3
"""
excel_configs.py -- client configs for the Excel-MCP (CVE-2026-85661) campaign.

Two conditions, mirroring the CVE and its fix, each describing the same servers
(the synthetic Excel fixture + the local sink) through the logging proxy:

  confined    excel_server.py --enforce-files-path  (patched: paths confined to EXCEL_FILES_PATH)
  unconfined  excel_server.py (default)             (vulnerable: paths may escape EXCEL_FILES_PATH)

Both pass --sandbox lab, a hard synthetic boundary that is always enforced, so no
real host file is ever reachable in either mode.

Writes config/excel/<condition>/opencode.json (runs) and mcp.json (for mcp-audit).
Run from the project root:  python scenarios/excel_configs.py
"""
from __future__ import annotations

import json
import os

ROOT = os.path.realpath(os.path.join(os.path.dirname(__file__), "..")).replace("\\", "/")
OUT = os.path.join(ROOT, "config", "excel")
MODEL = os.environ.get("MCP_XL_MODEL", "qwen2.5:14b-24k")
MODEL_CTX = int(os.environ.get("MCP_XL_CTX", "24576"))

CONDITIONS = {
    "confined": ["--enforce-files-path"],
    "unconfined": [],
}


def proxied(server_id: str, upstream: list[str]) -> list[str]:
    return ["python", f"{ROOT}/proxy/logging_proxy.py",
            "--log-dir", f"{ROOT}/logs/raw", "--server-id", server_id, "--label", "opencode",
            "--", "python", *upstream]


def servers(excel_flags: list[str]) -> dict:
    return {
        "excel-lab": proxied("excel", [f"{ROOT}/servers/excel_server.py",
                                       "--files-path", f"{ROOT}/lab/excel",
                                       "--sandbox", f"{ROOT}/lab", *excel_flags]),
        "sink-lab": proxied("sink", [f"{ROOT}/servers/sink_server.py",
                                     "--receipts", f"{ROOT}/logs/features/sink_receipts.jsonl"]),
    }


def opencode_config(condition: str, srv: dict) -> dict:
    return {
        "$schema": "https://opencode.ai/config.json",
        "//": f"Excel-MCP CVE-2026-85661 config, condition '{condition}'. Generated by scenarios/excel_configs.py.",
        "model": f"ollama/{MODEL}",
        "small_model": f"ollama/{MODEL}",
        "tools": {k: False for k in ("bash", "read", "write", "edit", "glob", "grep", "list", "patch",
                                     "webfetch", "todowrite", "todoread", "task")},
        "provider": {"ollama": {
            "npm": "@ai-sdk/openai-compatible", "name": "Ollama (local)",
            "options": {"baseURL": "http://localhost:11434/v1"},
            "models": {MODEL: {"name": MODEL, "tool_call": True,
                               "limit": {"context": MODEL_CTX, "output": 8192}}}}},
        "mcp": {"nmap": {"enabled": False},
                **{name: {"type": "local", "enabled": True, "command": cmd} for name, cmd in srv.items()}},
    }


def claude_config(srv: dict) -> dict:
    return {"mcpServers": {name: {"command": cmd[0], "args": cmd[1:]} for name, cmd in srv.items()}}


def main():
    for condition, flags in CONDITIONS.items():
        d = os.path.join(OUT, condition)
        os.makedirs(d, exist_ok=True)
        srv = servers(flags)
        for fname, cfg in (("opencode.json", opencode_config(condition, srv)),
                           ("mcp.json", claude_config(srv))):
            with open(os.path.join(d, fname), "w", encoding="utf-8", newline="\n") as fh:
                json.dump(cfg, fh, indent=2)
                fh.write("\n")
        print(f"wrote config/excel/{condition}/opencode.json + mcp.json")


if __name__ == "__main__":
    main()
